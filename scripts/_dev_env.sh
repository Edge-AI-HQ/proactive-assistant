#!/usr/bin/env bash

# Shared implementation for dev-env-cn.sh and dev-env-us.sh.
# The public entrypoints may be executed (persistent change, effective in new
# terminals) or sourced (also updates the current shell).

pinai_switch_dev_region() {
  local region="$1"
  local config_base
  local config_dir
  local env_file
  local make_file
  local shell_rc
  local escaped_env_file

  config_base="${PINAI_DEV_CONFIG_HOME:-${XDG_CONFIG_HOME:-$HOME/.config}}"
  config_dir="$config_base/pinai"
  env_file="$config_dir/dev-region.env"
  make_file="$config_dir/dev-region.mk"

  mkdir -p "$config_dir"

  case "$region" in
    cn)
      cat >"$env_file" <<'EOF'
# Generated by PIN AI scripts/dev-env-cn.sh. Do not put secrets here.
# DaoCloud image aliases are for local development only; CI/Fly use the
# Dockerfile defaults and production should use an owned registry.
export PINAI_DEV_REGION=cn
export PINAI_UV_DEFAULT_INDEX=https://mirrors.tuna.tsinghua.edu.cn/pypi/web/simple/
export PINAI_PYTHON_BASE_IMAGE=docker.m.daocloud.io/library/python:3.12-slim
export PINAI_NODE_BASE_IMAGE=docker.m.daocloud.io/library/node:20-slim
export PINAI_NGINX_BASE_IMAGE=docker.m.daocloud.io/library/nginx:1.27-alpine
export PINAI_PGVECTOR_IMAGE=docker.m.daocloud.io/pgvector/pgvector:pg15
export PINAI_REDIS_IMAGE=docker.m.daocloud.io/library/redis:7-alpine
export PINAI_UV_BASE_IMAGE=ghcr.m.daocloud.io/astral-sh/uv:0.11.21
export NPM_REGISTRY=https://registry.npmmirror.com
export npm_config_registry=https://registry.npmmirror.com
export npm_config_disturl=https://npmmirror.com/mirrors/node
export PIP_INDEX_URL=https://mirrors.tuna.tsinghua.edu.cn/pypi/web/simple
unset PIP_EXTRA_INDEX_URL
if [ -z "${PINAI_DEV_NO_PROXY_BASE+x}" ]; then
  export PINAI_DEV_NO_PROXY_BASE="${NO_PROXY:-${no_proxy:-}}"
fi
PINAI_CN_NO_PROXY=localhost,127.0.0.1,::1,.tsinghua.edu.cn,.npmmirror.com,.daocloud.io
export NO_PROXY="${PINAI_DEV_NO_PROXY_BASE:+$PINAI_DEV_NO_PROXY_BASE,}$PINAI_CN_NO_PROXY"
export no_proxy="$NO_PROXY"
unset PINAI_CN_NO_PROXY
export HOMEBREW_API_DOMAIN=https://mirrors.tuna.tsinghua.edu.cn/homebrew-bottles/api
export HOMEBREW_BOTTLE_DOMAIN=https://mirrors.tuna.tsinghua.edu.cn/homebrew-bottles
export HOMEBREW_PIP_INDEX_URL=https://mirrors.tuna.tsinghua.edu.cn/pypi/web/simple
export ELECTRON_MIRROR=https://npmmirror.com/mirrors/electron/
export ELECTRON_BUILDER_BINARIES_MIRROR=https://npmmirror.com/mirrors/electron-builder-binaries/
EOF
      cat >"$make_file" <<'EOF'
# Generated by PIN AI scripts/dev-env-cn.sh. Do not put secrets here.
# DaoCloud image aliases are for local development only.
PINAI_DEV_REGION := cn
NPM_REGISTRY := https://registry.npmmirror.com
PINAI_UV_DEFAULT_INDEX := https://mirrors.tuna.tsinghua.edu.cn/pypi/web/simple/
PINAI_PYTHON_BASE_IMAGE := docker.m.daocloud.io/library/python:3.12-slim
PINAI_NODE_BASE_IMAGE := docker.m.daocloud.io/library/node:20-slim
PINAI_NGINX_BASE_IMAGE := docker.m.daocloud.io/library/nginx:1.27-alpine
PINAI_PGVECTOR_IMAGE := docker.m.daocloud.io/pgvector/pgvector:pg15
PINAI_REDIS_IMAGE := docker.m.daocloud.io/library/redis:7-alpine
PINAI_UV_BASE_IMAGE := ghcr.m.daocloud.io/astral-sh/uv:0.11.21
npm_config_registry := https://registry.npmmirror.com
npm_config_disturl := https://npmmirror.com/mirrors/node
PIP_INDEX_URL := https://mirrors.tuna.tsinghua.edu.cn/pypi/web/simple
ELECTRON_MIRROR := https://npmmirror.com/mirrors/electron/
ELECTRON_BUILDER_BINARIES_MIRROR := https://npmmirror.com/mirrors/electron-builder-binaries/
export PINAI_DEV_REGION PINAI_UV_DEFAULT_INDEX NPM_REGISTRY npm_config_registry npm_config_disturl
export PINAI_PYTHON_BASE_IMAGE PINAI_NODE_BASE_IMAGE PINAI_NGINX_BASE_IMAGE
export PINAI_PGVECTOR_IMAGE PINAI_REDIS_IMAGE PINAI_UV_BASE_IMAGE
export PIP_INDEX_URL ELECTRON_MIRROR ELECTRON_BUILDER_BINARIES_MIRROR
EOF
      ;;
    us)
      cat >"$env_file" <<'EOF'
# Generated by PIN AI scripts/dev-env-us.sh. Do not put secrets here.
export PINAI_DEV_REGION=us
export PINAI_UV_DEFAULT_INDEX=https://pypi.org/simple
export PINAI_PYTHON_BASE_IMAGE=python:3.12-slim
export PINAI_NODE_BASE_IMAGE=node:20-slim
export PINAI_NGINX_BASE_IMAGE=nginx:1.27-alpine
export PINAI_PGVECTOR_IMAGE=pgvector/pgvector:pg15
export PINAI_REDIS_IMAGE=redis:7-alpine
export PINAI_UV_BASE_IMAGE=ghcr.io/astral-sh/uv:0.11.21
export NPM_REGISTRY=https://registry.npmjs.org
export npm_config_registry=https://registry.npmjs.org
export PIP_INDEX_URL=https://pypi.org/simple
unset PIP_EXTRA_INDEX_URL
if [ -n "${PINAI_DEV_NO_PROXY_BASE+x}" ]; then
  if [ -n "$PINAI_DEV_NO_PROXY_BASE" ]; then
    export NO_PROXY="$PINAI_DEV_NO_PROXY_BASE"
    export no_proxy="$PINAI_DEV_NO_PROXY_BASE"
  else
    unset NO_PROXY
    unset no_proxy
  fi
  unset PINAI_DEV_NO_PROXY_BASE
fi
unset npm_config_disturl
unset HOMEBREW_API_DOMAIN
unset HOMEBREW_BOTTLE_DOMAIN
unset HOMEBREW_PIP_INDEX_URL
unset ELECTRON_MIRROR
unset ELECTRON_BUILDER_BINARIES_MIRROR
EOF
      cat >"$make_file" <<'EOF'
# Generated by PIN AI scripts/dev-env-us.sh. Do not put secrets here.
PINAI_DEV_REGION := us
NPM_REGISTRY := https://registry.npmjs.org
PINAI_UV_DEFAULT_INDEX := https://pypi.org/simple
PINAI_PYTHON_BASE_IMAGE := python:3.12-slim
PINAI_NODE_BASE_IMAGE := node:20-slim
PINAI_NGINX_BASE_IMAGE := nginx:1.27-alpine
PINAI_PGVECTOR_IMAGE := pgvector/pgvector:pg15
PINAI_REDIS_IMAGE := redis:7-alpine
PINAI_UV_BASE_IMAGE := ghcr.io/astral-sh/uv:0.11.21
npm_config_registry := https://registry.npmjs.org
PIP_INDEX_URL := https://pypi.org/simple
export PINAI_DEV_REGION PINAI_UV_DEFAULT_INDEX NPM_REGISTRY npm_config_registry PIP_INDEX_URL
export PINAI_PYTHON_BASE_IMAGE PINAI_NODE_BASE_IMAGE PINAI_NGINX_BASE_IMAGE
export PINAI_PGVECTOR_IMAGE PINAI_REDIS_IMAGE PINAI_UV_BASE_IMAGE
EOF
      ;;
    *)
      echo "ERROR: unsupported region '$region' (expected cn or us)." >&2
      return 2
      ;;
  esac

  if [ -n "${PINAI_DEV_SHELL_RC:-}" ]; then
    shell_rc="$PINAI_DEV_SHELL_RC"
  else
    case "${SHELL:-}" in
      */zsh) shell_rc="${ZDOTDIR:-$HOME}/.zshrc" ;;
      */bash)
        if [ "$(uname -s)" = "Darwin" ]; then
          shell_rc="$HOME/.bash_profile"
        else
          shell_rc="$HOME/.bashrc"
        fi
        ;;
      *) shell_rc="$HOME/.profile" ;;
    esac
  fi

  mkdir -p "$(dirname "$shell_rc")"
  [ -e "$shell_rc" ] || : >"$shell_rc"
  if ! grep -Fq '# PIN AI dev-region (managed)' "$shell_rc"; then
    printf -v escaped_env_file '%q' "$env_file"
    {
      printf '\n# PIN AI dev-region (managed)\n'
      printf '[ -f %s ] && . %s\n' "$escaped_env_file" "$escaped_env_file"
    } >>"$shell_rc"
  fi

  # When the entrypoint itself is sourced, these exports/unsets also update
  # the caller. When it is executed, the persistent shell hook still makes the
  # profile effective in every newly opened terminal.
  . "$env_file"

  echo "PIN AI development region: $region"
  echo "  npm:  $NPM_REGISTRY"
  echo "  pip:  $PIP_INDEX_URL"
  if [ "$region" = "cn" ]; then
    echo "  uv in Docker builds: $PINAI_UV_DEFAULT_INDEX"
    echo "  Homebrew/Electron: China mirrors enabled"
    echo "  Docker bases: DaoCloud mirror enabled"
    echo "  proxy bypass: *.tsinghua.edu.cn, *.npmmirror.com, *.daocloud.io"
    if command -v scutil >/dev/null 2>&1 \
      && scutil --proxy 2>/dev/null | grep -Eq 'HTTP(S)?Enable : 1'; then
      echo "  warning: macOS system proxy is active"
    fi
    echo "  note: VPN TUN/full-tunnel mode still needs China/GeoIP DIRECT routing"
  else
    echo "  uv in Docker builds: https://pypi.org/simple"
    echo "  Homebrew/Electron: official defaults restored"
  fi
  echo "  persisted in: $env_file"
  echo "  Make config:  $make_file"
  echo ""
  echo "New terminals and subsequent make commands use this region."
  echo "To update this terminal too, run: source scripts/dev-env-$region.sh"
}
