#!/usr/bin/env node

import { promises as fs } from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";

const __filename = fileURLToPath(import.meta.url);
const __dirname = path.dirname(__filename);
const repoRoot = path.resolve(__dirname, "..");

const skillsDir = path.join(
  repoRoot,
  "infra",
  "container-manager",
  "images",
  "openclaw",
  "skills",
);
const outputFile = path.join(
  repoRoot,
  "apis",
  "src",
  "domain",
  "skills",
  "generated_custom_skill_keys.ts",
);

const readSkillKeys = async () => {
  try {
    const entries = await fs.readdir(skillsDir, { withFileTypes: true });
    return entries
      .filter((entry) => entry.isDirectory() && !entry.name.startsWith("."))
      .map((entry) => entry.name)
      .sort((a, b) => a.localeCompare(b));
  } catch (error) {
    const code =
      typeof error === "object" && error && "code" in error
        ? String(error.code)
        : "";
    if (code !== "ENOENT") throw error;

    // Docker API image build context may not include infra/skills.
    // In that case keep using the already committed generated file.
    try {
      const existing = await fs.readFile(outputFile, "utf8");
      const keys = Array.from(
        existing.matchAll(/^\s*"([^"]+)",?\s*$/gm),
        (m) => m[1],
      ).filter(Boolean);
      if (keys.length > 0) {
        console.warn(
          `skills dir missing at ${skillsDir}; reusing ${keys.length} keys from existing manifest.`,
        );
        return keys.sort((a, b) => a.localeCompare(b));
      }
    } catch {
      // fall through and generate empty list
    }

    console.warn(
      `skills dir missing at ${skillsDir}; generating empty manifest fallback.`,
    );
    return [];
  }
};

const buildSource = (keys) => {
  const quoted = keys.map((key) => `  "${key}",`).join("\n");
  return `// Auto-generated by scripts/sync-skills-manifest.mjs
// Do not edit manually.

export const CUSTOM_SKILL_KEYS = [
${quoted}
] as const;
`;
};

const main = async () => {
  const keys = await readSkillKeys();
  const source = buildSource(keys);
  await fs.writeFile(outputFile, source, "utf8");
  console.log(
    `Updated ${path.relative(repoRoot, outputFile)} with ${keys.length} skill keys.`,
  );
};

main().catch((error) => {
  console.error("Failed to sync skills manifest:", error);
  process.exitCode = 1;
});
